/*
页面获取流程
获取页面 (Fetch/Pin)：
B+ 树遍历索引需要特定页面时，向 BufferPool 发起请求（通过 page_id 或页号）。
命中与加载：命中：若页面已在内存中，直接返回内存地址。
未命中：BufferPool 从磁盘读取该页，并将其加载至空闲缓存槽位中。若缓冲池已满，则执行替换算法（如 LRU 或 Clock）淘汰冷数据页。
加锁保护 (Pin/Fix)：BufferPool 为请求页加锁（Pin 或 Fix），防止在 B+ 树遍历期间该页被意外换出。
页面修改流程
修改脏页：获取页面后，B+ 树直接在内存中执行插入、删除或更新操作。
标记脏页：B+ 树完成修改后，需通知 BufferPool 将该页标记为“脏页 (Dirty Page)”，以便后台线程稍后将其刷回磁盘。
并发与事务控制：结合日志先行策略（WAL），BufferPool 会确保 redo log 先于数据页落盘。页面释放后调用 unfix/unpin 解除锁定，供其他并发事务访问。
*/